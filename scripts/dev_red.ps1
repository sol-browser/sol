# Builds Red against the fast-iteration engine (out\Dev_x64, component build) into build\devtest.
# The CEF root (devdist) is a copy of the pinned distribution with the checkout's current headers,
# wrapper sources and import library; the component DLLs and resources are copied next to Red.
# -ClientOnly reuses an existing devdist; it still stages the matching component runtime after build.
# Close any running build\devtest Red first (its DLL is locked). Run the result with
#   build\devtest\apps\desktop\Release\sol.exe --workspace --profile-dir=E:\red-test-profile
# (a separate profile: the user's own Red and profile are never touched), or point the probes at
# it: RED_BROWSER_TEST_EXE=<that exe>, RED_PROBE_DISPLAY=secondary.
# Known dev-only issue: a DCHECK at exit ("Object reference incorrectly held at CefShutdown",
# exit code 0x80000003); probes report it as the exit code. Not present in official builds.
param([ValidatePattern('^[A-Za-z]:\\[^ ]+$')][string]$WorkDirectory = 'E:\cef-build',
      # Native-client-only fixes reuse the existing dev SDK, without writing the engine checkout/devdist.
      [switch]$ClientOnly,
      # A separate output keeps a running manual dev browser available while preparing its replacement.
      [ValidatePattern('^[A-Za-z0-9_-]+$')][string]$BuildDirectory = 'devtest')
$ErrorActionPreference = 'Stop'
$repo = Split-Path -Parent $PSScriptRoot
$src = "$WorkDirectory\code\chromium\src"
$out = "$src\out\Dev_x64"
$dist = "$WorkDirectory\devdist"
$vswhere = Join-Path ${env:ProgramFiles(x86)} 'Microsoft Visual Studio\Installer\vswhere.exe'
$vsRoot = & $vswhere -latest -products * -requires Microsoft.VisualStudio.Component.VC.Tools.x86.x64 -property installationPath
Import-Module (Join-Path $vsRoot 'Common7\Tools\Microsoft.VisualStudio.DevShell.dll')
Enter-VsDevShell -VsInstallPath $vsRoot -SkipAutomaticLocation -DevCmdArguments '-arch=x64 -host_arch=x64' | Out-Null
$cmake = Join-Path $vsRoot 'Common7\IDE\CommonExtensions\Microsoft\CMake\CMake\bin\cmake.exe'
$env:PATH = (Join-Path $vsRoot 'Common7\IDE\CommonExtensions\Microsoft\CMake\Ninja') + ";$env:PATH"
# Fresh copy each time, then overlay (never mirror: the distribution's own CMake files and the
# headers generated by the build must stay).
if (!$ClientOnly) {
  if ([IO.Path]::GetFullPath($dist) -ne [IO.Path]::GetFullPath((Join-Path $WorkDirectory 'devdist'))) { throw 'Unexpected dev SDK directory' }
  if (Test-Path $dist) { Remove-Item -Recurse -Force -LiteralPath $dist }
  robocopy "$repo\third_party\cef" $dist /E /NFL /NDL /NJH /NJS | Out-Null
  # Only what API patches change (include/base is transformed when CEF packs a distribution).
  robocopy "$src\cef\include" "$dist\include" *.h /NFL /NDL /NJH /NJS | Out-Null
  robocopy "$src\cef\include\capi" "$dist\include\capi" /E /NFL /NDL /NJH /NJS | Out-Null
  robocopy "$src\cef\include\views" "$dist\include\views" /E /NFL /NDL /NJH /NJS | Out-Null
  robocopy "$out\gen\cef\include" "$dist\include" /E /NFL /NDL /NJH /NJS | Out-Null
  robocopy "$src\cef\libcef_dll" "$dist\libcef_dll" /E /XF CMakeLists.txt BUILD.gn /NFL /NDL /NJH /NJS | Out-Null
  Copy-Item "$out\libcef.dll.lib" "$dist\Release\libcef.lib" -Force
} elseif (!(Test-Path -LiteralPath "$dist\include\cef_browser.h")) {
  throw 'Existing dev SDK required for -ClientOnly; run the full dev_red.ps1 setup first'
}
$build = Join-Path "$repo\build" $BuildDirectory
Push-Location (Join-Path $repo 'apps\browser-ui')
try {
  & npm.cmd run build
  if ($LASTEXITCODE) { throw 'Browser UI build failed' }
} finally { Pop-Location }
& $cmake -S $repo -B $build -G Ninja -DCMAKE_BUILD_TYPE=Release "-DCEF_ROOT=$dist" | Out-Null
if ($LASTEXITCODE) { throw 'configure failed' }
& $cmake --build $build --parallel 8 2>&1 | Select-String -Pattern 'error|FAILED' | Select-Object -First 30
if ($LASTEXITCODE) { throw 'Sol build failed' }
$target = "$build\apps\desktop\Release"
Get-ChildItem $out -Filter *.dll | Copy-Item -Destination $target -Force
foreach ($name in 'icudtl.dat', 'v8_context_snapshot.bin', 'resources.pak', 'chrome_100_percent.pak', 'chrome_200_percent.pak') {
  if (Test-Path "$out\$name") { Copy-Item "$out\$name" $target -Force }
}
robocopy "$out\locales" "$target\locales" /MIR /NFL /NDL /NJH /NJS | Out-Null
# The launcher must come from the same build (its handle verifier must be the component base's).
Copy-Item "$out\bootstrap.exe" "$target\sol.exe" -Force
& editbin /nologo /STACK:0x800000 "$target\sol.exe" | Out-Null
"$BuildDirectory ready: $target\sol.exe"
