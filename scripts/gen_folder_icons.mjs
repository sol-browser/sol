function paths(name, size) {
  let svg;
  try { svg = readFileSync(join(packageDir, 'icons', `${name}_${size}_filled.svg`), 'utf8'); } catch { return undefined; }
  const body = svg.replace(/^<svg[^>]*>|<\/svg>\s*$/gu, '');
  const found = [...body.matchAll(/<path d="([^"]+)"\/>/gu)].map(match => match[1]);
  // Only plain single-colour paths: anything else would be drawn wrongly or carry markup.
  if (!found.length || body.replace(/<path d="[^"]+"\/>/gu, '') !== '' || found.some(d => !/^[0-9MmLlHhVvCcSsQqTtAaZz .,-]+$/u.test(d)))
    throw new Error(`${name}_${size}_filled.svg is not plain paths`);
  return found;
}

let out = `// Generated by scripts/gen_folder_icons.mjs from @fluentui/svg-icons ${version} — do not edit.
// Fluent UI System Icons, Copyright (c) Microsoft Corporation, MIT License
// (https://github.com/microsoft/fluentui-system-icons/blob/main/LICENSE).
/** Filled glyph paths by catalog id: [viewBox size, paths]. "small" is drawn on the folder, "large" in the picker. */
export const FOLDER_ICON_PATHS: Readonly<Record<string, { small: readonly [number, readonly string[]]; large: readonly [number, readonly string[]] }>> = {\n`;
for (const [id, name] of Object.entries(GLYPHS)) {
  const large = paths(name, 20);
  if (!large) throw new Error(`Missing ${name}_20_filled.svg`);
  const small = paths(name, 16);
  out += `  ${JSON.stringify(id)}: { small: ${small ? `[16, ${JSON.stringify(small)}]` : `[20, ${JSON.stringify(large)}]`}, large: [20, ${JSON.stringify(large)}] },\n`;
}
out += '};\n';
writeFileSync(join(root, 'apps/browser-ui/src/folder-icon-paths.ts'), out);
console.log(`folder-icon-paths.ts: ${Object.keys(GLYPHS).length} glyphs from @fluentui/svg-icons ${version}`);
