"""Generate the offline emoji-only picker from pinned Unicode/CLDR data."""
import hashlib
import json
from pathlib import Path
import re
from urllib.request import urlopen

ROOT=Path(__file__).resolve().parent.parent
MANIFEST=Path(__file__).with_name('emoji-catalog-sources.json')

def main():
    sources=json.loads(MANIFEST.read_text(encoding='utf-8'))
    content={}
    for key,source in sources.items():
        data=urlopen(source['url'],timeout=30).read()
        if hashlib.sha256(data).hexdigest()!=source['sha256']:
            raise ValueError('Source checksum changed: '+source['url'])
        content[key]=data.decode('utf-8')
    annotations={}
    for key,root in [('ru','annotations'),('ruDerived','annotationsDerived')]:
        annotations.update(json.loads(content[key])[root]['annotations'])
    annotations={k.replace('\ufe0f',''):v for k,v in annotations.items()}
    groups=[];entries=[]
    for line in content['emoji'].splitlines():
        if line.startswith('# group: '):
            group=line.removeprefix('# group: ')
            if group!='Component': groups.append(group)
        match=re.match(r'^([0-9A-F ]+)\s*;\s*fully-qualified\s*#\s*\S+\s+E[0-9.]+\s+(.+)$',line)
        if not match: continue
        emoji=''.join(chr(int(c,16)) for c in match[1].split())
        if len(emoji)>16 or len(emoji.encode('utf8'))>128: continue
        en=match[2];ru=annotations.get(emoji.replace('\ufe0f',''),{})
        label=(ru.get('tts')or[en])[0]
        search=' '.join(dict.fromkeys([emoji,en,label,*ru.get('default',[])]))
        entries.append([emoji,label,search,groups.index(group)])
    assert len(entries)>3500 and len(groups)==9 and len({e[0] for e in entries})==len(entries)
    output=ROOT/'apps/browser-ui/src/emoji-catalog.ts'
    header='// Generated by scripts/generate_emoji_catalog.py. Unicode17.0 / CLDR48.0.\n// Unicode License V3: public/licenses/unicode-emoji.txt; source hashes in scripts/emoji-catalog-sources.json.\n'
    output.write_text(header+"import type {EmojiRecord} from './emoji-picker-model';\nexport const EMOJI_CATALOG:EmojiRecord[]=\n"+json.dumps(entries,ensure_ascii=False,separators=(',',':'))+';\n',encoding='utf8')
    (ROOT/'apps/browser-ui/public/licenses/unicode-emoji.txt').write_text(content['license'],encoding='utf8')
    print(json.dumps({'entries':len(entries),'groups':groups,'bytes':output.stat().st_size}))

if __name__=='__main__':main()
