# Pins a Streaming DRM component release of sol-browser/streaming-drm in
# apps/desktop/src/integrations/protected_media_release.h: Sol downloads that
# archive when a person turns Streaming DRM on and accepts it only with the
# pinned size and SHA-256 (docs/codecs.md#protected-content-install).
# The release is built and VMP-signed by that repository's Release workflow.
# This script downloads the archive itself and checks it against the
# release's own release.json and .sha256 before writing the pin.
param([Parameter(Mandatory)][ValidatePattern('^\d+\.\d+\.\d+-\d+$')][string]$Id)
$ErrorActionPreference = 'Stop'
$ProgressPreference = 'SilentlyContinue'
$root = Split-Path $PSScriptRoot -Parent
$base = "https://github.com/sol-browser/streaming-drm/releases/download/$Id"
$work = Join-Path $root "artifacts/streaming-drm/$Id"
New-Item -ItemType Directory -Force -Path $work | Out-Null

$metadata = Join-Path $work 'release.json'
Invoke-WebRequest -UseBasicParsing -Uri "$base/release.json" -OutFile $metadata
$release = Get-Content -LiteralPath $metadata -Raw | ConvertFrom-Json
$expectedName = "Sol-Streaming-DRM-$Id-win-x64.zip"
if ($release.id -ne $Id -or $release.file -ne $expectedName -or $release.sha256 -notmatch '^[0-9a-f]{64}$' -or
    [long]$release.size -le 0 -or [long]$release.installedSize -le [long]$release.size -or
    $release.signature -notmatch '^Signature is valid:\s+streaming') {
    throw "Unexpected release.json for $Id"
}

$archive = Join-Path $work $release.file
if (!(Test-Path -LiteralPath $archive) -or (Get-Item -LiteralPath $archive).Length -ne [long]$release.size) {
    Invoke-WebRequest -UseBasicParsing -Uri "$base/$($release.file)" -OutFile $archive
}
$hash = (Get-FileHash -LiteralPath $archive -Algorithm SHA256).Hash.ToLowerInvariant()
$sums = (Invoke-WebRequest -UseBasicParsing -Uri "$base/$($release.file).sha256").Content
if ($sums -is [byte[]]) { $sums = [Text.Encoding]::ASCII.GetString($sums) }
if ((Get-Item -LiteralPath $archive).Length -ne [long]$release.size -or $hash -ne $release.sha256 -or
    $sums.Trim() -ne "$hash  $($release.file)") {
    throw "The downloaded archive does not match release $Id"
}

$url = "$base/$($release.file)"
@"
#pragma once
// Generated by scripts/pin_streaming_drm.ps1 from sol-browser/streaming-drm
// release $Id (castLabs ECS $($release.ecs), source $($release.commit)).
// The archive Sol downloads for Streaming DRM (docs/codecs.md#protected-content-install).
namespace red::protected_media_release {
inline constexpr char kId[] = "$Id";
inline constexpr char kUrl[] = "$url";
inline constexpr char kSha256[] = "$hash";
inline constexpr unsigned long long kSize = $([long]$release.size)ull;
inline constexpr unsigned long long kInstalledSize = $([long]$release.installedSize)ull;
}  // namespace red::protected_media_release
"@ | Set-Content -LiteralPath (Join-Path $root 'apps/desktop/src/integrations/protected_media_release.h') -Encoding ascii
Write-Output "Pinned $Id`: $hash, $([long]$release.size) bytes, $([long]$release.installedSize) bytes installed"
Write-Output "Archive for loopback tests: $archive"
