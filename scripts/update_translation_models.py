"""Generates Sol's translation model catalog from Mozilla's model registry (docs/page-translation.md).

Sol downloads Firefox's Bergamot models (MPL 2.0) on demand, one direction at a time. This script picks
the desktop release model for every pair, pins every file by the SHA-256 of its uncompressed bytes and
writes apps/desktop/src/translation/model_catalog.inc. The registry gives the model's hash; the lexical
shortlist and vocabularies are downloaded once here to hash them.

Usage: python scripts/update_translation_models.py [--registry models.json] [--pairs de-en,en-uk]
"""
import argparse
import concurrent.futures
import gzip
import hashlib
import json
from pathlib import Path
import re
import urllib.request

ROOT = Path(__file__).resolve().parents[1]
REGISTRY = 'https://storage.googleapis.com/moz-fx-translations-data--303e-prod-translations-data/db/models.json'
OUTPUT = ROOT / 'apps/desktop/src/translation/model_catalog.inc'
CODE = re.compile(r'^[a-z]{2,3}(_[a-z]{4})?$')
PATH = re.compile(r'^models/[A-Za-z0-9_./-]+\.gz$')


def fetch(url: str) -> bytes:
    with urllib.request.urlopen(urllib.request.Request(url, headers={'User-Agent': 'sol-catalog'}), timeout=120) as response:
        return response.read()


def uncompressed(base: str, path: str) -> tuple[str, int]:
    data = gzip.decompress(fetch(f'{base}/{path}'))
    return hashlib.sha256(data).hexdigest(), len(data)


def choose(records: list[dict]) -> dict | None:
    # Firefox desktop ships "Release Desktop" where a pair has one, otherwise "Release".
    released = [r for r in records if r.get('releaseStatus') in ('Release Desktop', 'Release')]
    released.sort(key=lambda r: r['releaseStatus'] != 'Release Desktop')
    return released[0] if released else None


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--registry')
    parser.add_argument('--pairs')
    args = parser.parse_args()
    registry = json.loads(Path(args.registry).read_text(encoding='utf-8') if args.registry else fetch(REGISTRY))
    base = registry['baseUrl'].rstrip('/')
    if not base.startswith('https://storage.googleapis.com/'): raise SystemExit(f'Unexpected model host: {base}')
    wanted = set(args.pairs.split(',')) if args.pairs else None
    entries = []
    for pair, records in sorted(registry['models'].items()):
        if wanted is not None and pair not in wanted: continue
        record = choose(records)
        if not record: continue
        source, target = record['sourceLanguage'], record['targetLanguage']
        if f'{source}-{target}' != pair or not CODE.match(source) or not CODE.match(target): raise SystemExit(f'Odd pair {pair}')
        files = record['files']
        vocab = files.get('vocab')
        src, trg = (vocab, None) if vocab else (files['srcVocab'], files['trgVocab'])
        for part in (files['model'], files['lexicalShortlist'], src, trg):
            if part and not PATH.match(part['path']): raise SystemExit(f'Odd path in {pair}: {part["path"]}')
        entries.append((pair, record, files, src, trg))

    def hashes(entry):
        pair, record, files, src, trg = entry
        model = files['model']
        out = {'model': (model['uncompressedHash'], model['uncompressedSize'])}
        for name, part in (('lex', files['lexicalShortlist']), ('src', src), ('trg', trg)):
            if part: out[name] = uncompressed(base, part['path'])
        print(f'{pair} ok', flush=True)
        return pair, out

    with concurrent.futures.ThreadPoolExecutor(8) as pool:
        hashed = dict(pool.map(hashes, entries))

    lines = [
        f'// Generated by scripts/update_translation_models.py from Mozilla\'s model registry ({registry.get("generated", "?")}).',
        '// Do not edit. Firefox Translations models, MPL 2.0, one direction each (docs/page-translation.md).',
        f'// {{from, to, architecture, {{path, sha256 of the uncompressed file, uncompressed size}} x model/shortlist/vocab/target vocab}}',
    ]
    quote = lambda s: json.dumps(s)
    for pair, record, files, src, trg in entries:
        h = hashed[pair]
        part = lambda p, key: '{%s, %s, %d}' % (quote(p['path']), quote(h[key][0]), h[key][1]) if p else '{"", "", 0}'
        lines.append('{%s, %s, %s, %s, %s, %s, %s},' % (
            quote(record['sourceLanguage']), quote(record['targetLanguage']), quote(record['architecture']),
            part(files['model'], 'model'), part(files['lexicalShortlist'], 'lex'), part(src, 'src'), part(trg, 'trg')))
    OUTPUT.write_text('\n'.join(lines) + '\n', encoding='utf-8')
    print(f'{len(entries)} pairs -> {OUTPUT}')


if __name__ == '__main__':
    main()
